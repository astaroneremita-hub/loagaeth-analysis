"""
89 - Are the Calls drawn from the Loagaeth's letter-world? (cross-entropy test of the coordinate theory)

A forum theory (relayed by the practitioner): the Enochian Calls were generated by pointing at specific letters
at specific LOCATIONS in the Loagaeth - each Call letter is a Loagaeth letter picked by coordinate. The strong,
letter-by-letter version needs the reception numbers (not digitised here). But a necessary consequence IS
testable: if the Calls are built from Loagaeth letters, the Calls should live in the Loagaeth's own letter-world
- a character model trained on the Loagaeth should predict the Calls better than a model trained on the
Watchtowers (a different Enochian corpus), and better than a shuffled-Loagaeth model.

We train an order-3 character model on each source and measure cross-entropy (bits/char) on each target. Lower =
the target fits that source's letter-flow. Compared: Loagaeth-model vs Watchtower-model vs shuffled-Loagaeth, on
the Calls, the Watchtower names, and (control) the Loagaeth itself.
"""
import json
import math
import random
from collections import defaultdict

import load
from a22_robustness_and_depth import base_book


def train(text, k=3):
    ctx = defaultdict(lambda: defaultdict(int))
    text = "^" * k + text + "$"
    for i in range(k, len(text)):
        ctx[text[i - k:i]][text[i]] += 1
    model = {}
    vocab = set(text)
    for c, d in ctx.items():
        tot = sum(d.values())
        model[c] = (d, tot)
    return model, vocab, k


def cross_entropy(model, target, k=3):
    m, vocab, k = model
    V = len(vocab)
    t = "^" * k + target + "$"
    bits, n = 0.0, 0
    for i in range(k, len(t)):
        c, ch = t[i - k:i], t[i]
        d, tot = m.get(c, ({}, 0))
        p = (d.get(ch, 0) + 1) / (tot + V)  # add-1 smoothing
        bits += -math.log2(p)
        n += 1
    return bits / n


def run():
    rng = random.Random(89)
    book = base_book()
    loag = "".join("".join(r for r in book[k] if r) for k in book)

    # Watchtower letters
    q = json.load(open(load.ROOT + "/engine/data/quadrados.json", encoding="utf-8"))
    tw = []
    def grab(o):
        if isinstance(o, str):
            tw.append("".join(ch for ch in o.upper() if ch.isalpha()))
        elif isinstance(o, list):
            for x in o:
                grab(x)
        elif isinstance(o, dict):
            for x in o.values():
                grab(x)
    grab(q)
    tw_text = "".join(tw)

    # Call words
    calls = json.load(open(load.ROOT + "/engine/data/chamadas.json", encoding="utf-8"))["chamadas"]
    cw = []
    for c in calls:
        for w in (c.get("palavras") or []):
            t = (w.get("tfr") or w.get("palavra") or "") if isinstance(w, dict) else (w or "")
            s = "".join(ch for ch in str(t).upper() if ch.isalpha())
            if s:
                cw.append(s)
    call_text = "".join(cw)

    loag_sh = list(loag)
    rng.shuffle(loag_sh)
    loag_sh = "".join(loag_sh)

    models = {
        "Loagaeth": train(loag),
        "Watchtowers": train(tw_text),
        "Loagaeth_shuffled": train(loag_sh),
    }
    targets = {"Chamadas": call_text, "Nomes_Torres": tw_text[:4000], "Loagaeth(controle)": loag[:8000]}

    table = {}
    for tname, ttext in targets.items():
        table[tname] = {mname: round(cross_entropy(model, ttext), 3) for mname, model in models.items()}

    calls_fit = table["Chamadas"]
    best = min(calls_fit, key=calls_fit.get)
    res = {
        "cross_entropy_bits_per_char": table,
        "note": "Linha = texto-alvo; coluna = modelo treinado nessa fonte; valor = bits/char (menor = o alvo "
                "encaixa melhor no fluxo de letras daquela fonte).",
        "calls_best_fit_model": best,
        "finding": (
            "As Chamadas encaixam melhor no modelo '%s' (%.2f bits/char) — Loagaeth %.2f, Torres %.2f, "
            "Loagaeth-embaralhado %.2f. %s" % (
                best, calls_fit[best], calls_fit["Loagaeth"], calls_fit["Watchtowers"], calls_fit["Loagaeth_shuffled"],
                "Isso apoia que as Chamadas compartilham o mundo-de-letras da Loagaeth (consistente com serem tiradas dela)."
                if best == "Loagaeth" and calls_fit["Loagaeth"] < calls_fit["Watchtowers"] - 0.05 else
                "As Chamadas NAO encaixam melhor na Loagaeth que nas Torres — o vinculo letra-a-letra nao aparece neste teste; os dois sao linguas enoquianas de textura parecida, mas a Chamada nao e mais 'Loagaeth' que 'Torre'.")),
    }
    load.save_result("89_calls_source", res)
    return res


if __name__ == "__main__":
    r = run()
    print("cross-entropy (bits/char) — linha=alvo, coluna=modelo:\n")
    print("%-20s %10s %12s %16s" % ("", "Loagaeth", "Watchtowers", "Loag_shuffled"))
    for t, row in r["cross_entropy_bits_per_char"].items():
        print("%-20s %10.3f %12.3f %16.3f" % (t, row["Loagaeth"], row["Watchtowers"], row["Loagaeth_shuffled"]))
    print("\n" + r["finding"])
